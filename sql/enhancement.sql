CREATE OR REPLACE TABLE COVID_PROJECT.PUBLIC.COVID_DAILY AS
SELECT
COALESCE(m.STANDARD_COUNTRY, c.COUNTRY) AS COUNTRY,
c.DATE,
c.YEAR,
SUM(CASE 
WHEN c.CASE_TYPE='confirmed'
THEN c.CASES 
ELSE 0 
END) AS CONFIRMED,
SUM(CASE 
WHEN c.CASE_TYPE='deaths'
THEN c.CASES 
ELSE 0 
END) AS DEATHS,
SUM(CASE 
WHEN c.CASE_TYPE='recovered'
THEN c.CASES 
ELSE 0 
END) AS RECOVERED,
SUM(CASE 
WHEN c.CASE_TYPE='active'
THEN c.CASES 
ELSE 0 
END) AS ACTIVE
FROM COVID_PROJECT.PUBLIC.COVID_CLEAN c
LEFT JOIN COVID_PROJECT.PUBLIC.COUNTRY_MAPPING m
ON c.COUNTRY = m.SOURCE_COUNTRY
GROUP BY
COALESCE(m.STANDARD_COUNTRY, c.COUNTRY),
c.DATE,
c.YEAR;